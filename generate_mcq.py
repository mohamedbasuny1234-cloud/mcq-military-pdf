        c.setFillColor(colors.HexColor('#ECF0F1'))
        c.setFont('Amiri-Bold', 22)
        c.drawCentredString(self.width / 2, text_y - 38*mm,
                            ar("الدفعة ١١٦ حربية"))

        # شرائط الرتبة
        ribbon_y = text_y - 60*mm
        ribbon_w = 90*mm
        ribbon_h = 4*mm
        ribbon_x = (self.width - ribbon_w) / 2

        c.setFillColor(colors.HexColor('#8B0000'))
        c.roundRect(ribbon_x, ribbon_y, ribbon_w, ribbon_h,
                    2*mm, fill=1, stroke=0)
        c.setFillColor(colors.HexColor('#D4AF37'))
        c.roundRect(ribbon_x, ribbon_y + ribbon_h - 1*mm,
                    ribbon_w, 1*mm, 0, fill=1, stroke=0)

        c.setFillColor(colors.HexColor('#D4AF37'))
        c.roundRect(ribbon_x + 5*mm, ribbon_y - 6*mm,
                    ribbon_w - 10*mm, ribbon_h, 2*mm, fill=1, stroke=0)

        # النجمة الذهبية
        star_cx = self.width / 2
        star_cy = ribbon_y - 15*mm
        star_r = 4*mm
        c.setFillColor(colors.HexColor('#D4AF37'))
        p = c.beginPath()
        for i in range(10):
            angle = math.pi/2 + i * math.pi/5
            r = star_r if i % 2 == 0 else star_r * 0.4
            x = star_cx + r * math.cos(angle)
            y = star_cy + r * math.sin(angle)
            if i == 0:
                p.moveTo(x, y)
            else:
                p.lineTo(x, y)
        p.close()
        c.drawPath(p, fill=1, stroke=0)

        # نقاط زخرفية
        c.setFillColor(colors.HexColor('#D4AF37'))
        c.setFillAlpha(0.3)
        for x_pos, y_pos in [(25*mm, self.height - 25*mm),
                              (self.width - 25*mm, self.height - 25*mm),
                              (25*mm, 25*mm),
                              (self.width - 25*mm, 25*mm)]:
            c.circle(x_pos, y_pos, 4*mm, fill=1, stroke=0)
        c.setFillAlpha(1)

        c.restoreState()


